// Generates `docs/decision-index.md`: where each numbered decision and each dated decision entry
// is recorded. Numbered decisions are spread over the decisions.md table, its archived rows
// (docs/archive/decisions-numbered.md), the archived simulator history and the archived progress
// session log.
//
//   bun scripts/decision-index.ts            # rewrite
//   bun scripts/decision-index.ts --check    # exit 1 if it would change

import { readFileSync, writeFileSync } from "node:fs";
import { committedText } from "./lib/generated";
import { repoPath } from "./lib/repo";

const OUT = "docs/decision-index.md";
const TITLE_MAX = 110;

export const DECISIONS = "docs/decisions.md";
export const NUMBERED_ARCHIVE = "docs/archive/decisions-numbered.md";
export const HISTORY = "docs/archive/simulator-history.md";
export const PROGRESS = "docs/archive/progress.md";
/** Files holding numbered `| D<n> |` table rows. */
const TABLES = [DECISIONS, NUMBERED_ARCHIVE];

type Place = { file: string; line: number; title: string };

function cell(text: string): string {
  const plain = text
    .replace(/\*\*|`|🛑|⚠️|✅|🆕/g, "")
    .replace(/\|/g, "\\|")
    .replace(/\s+/g, " ")
    .trim();
  return plain.length > TITLE_MAX ? `${plain.slice(0, TITLE_MAX - 1).trimEnd()}…` : plain;
}

/** The index page, built from the repo-relative files `read` returns. */
export function decisionIndex(read: (file: string) => string): {
  body: string;
  numbered: number;
  dated: number;
} {
  const linesOf = (file: string) => read(file).split("\n");
  const numbered = new Map<number, Place[]>();
  const dated: Place[] = [];

  const record = (id: number, place: Place) => {
    const places = numbered.get(id) ?? [];
    places.push(place);
    numbered.set(id, places);
  };

  for (const file of TABLES) {
    linesOf(file).forEach((text, i) => {
      const row = /^\| (?:\*\*)?D(\d+)[a-z]?(?:\*\*)? \| (?:\d{4}-\d{2}-\d{2} \| )?([^|]*)\|/.exec(
        text,
      );
      if (row) record(Number(row[1]), { file, line: i + 1, title: row[2] ?? "" });
    });
  }

  linesOf(DECISIONS).forEach((text, i) => {
    const entry = /^### (\d{4}-\d{2}-\d{2}) — (.*)$/.exec(text);
    if (entry)
      dated.push({ file: DECISIONS, line: i + 1, title: `${entry[1]} | ${cell(entry[2] ?? "")}` });
  });

  linesOf(HISTORY).forEach((text, i) => {
    const heading = /^## D(\d+) — (.*)$/.exec(text);
    if (heading)
      record(Number(heading[1]), { file: HISTORY, line: i + 1, title: heading[2] ?? "" });
  });

  const progress = linesOf(PROGRESS);
  progress.forEach((text, i) => {
    const session = /^### \d{4}-\d{2}-\d{2} — build session #\d+ \((.*)\)$/.exec(text);
    const id = session && /\bD(\d+)\b/.exec(session[1] ?? "");
    if (session && id) {
      const named = (session[1] ?? "").replace(/^.*?\bD\d+\b[,:]?\s*/, "");
      const lead = progress.slice(i + 1, i + 4).find((line) => line.trim() !== "") ?? "";
      const title = named || (/^\*\*(.+?)\*\*/.exec(lead)?.[1] ?? "");
      record(Number(id[1]), { file: PROGRESS, line: i + 1, title });
    }
  });

  const where = (place: Place) => `${place.file.replace(/^docs\//, "")}:${place.line}`;

  const numberedRows = [...numbered.entries()]
    .sort(([a], [b]) => a - b)
    .map(([id, places]) => {
      const title = places.find((place) => place.title.trim() !== "")?.title ?? "";
      return `| D${id} | ${cell(title)} | ${places.map(where).join(", ")} |`;
    });

  const body = `# Decision index

Generated by \`bun scripts/decision-index.ts\` from \`decisions.md\`, \`archive/decisions-numbered.md\`,
\`archive/simulator-history.md\` and \`archive/progress.md\`; do not edit by hand. \`check:static\`
fails when it is stale, so rerun the script after adding a decision.

## Dated entries (\`decisions.md\`)

| Date | Decision | Where |
|---|---|---|
${dated.map((place) => `| ${place.title} | ${where(place)} |`).join("\n")}

## Numbered decisions

D1-D100 are in \`decisions.md\`; D101-D647 in \`archive/decisions-numbered.md\`. Titles are
truncated. Where a decision has several records, all are listed. A number missing here has no
heading of its own; grep the archive for it.

| # | Title | Where |
|---|---|---|
${numberedRows.join("\n")}
`;
  return { body, numbered: numbered.size, dated: dated.length };
}

if (import.meta.main) {
  const { body, numbered, dated } = decisionIndex((file) => readFileSync(repoPath(file), "utf8"));
  if (process.argv.includes("--check")) {
    if (committedText(OUT) !== body) {
      console.error(`${OUT} is STALE — run: bun scripts/decision-index.ts`);
      process.exit(1);
    }
    console.log(`${OUT} is current (${numbered} numbered, ${dated} dated).`);
  } else {
    writeFileSync(repoPath(OUT), body);
    console.log(`${OUT} written — ${numbered} numbered, ${dated} dated.`);
  }
}
