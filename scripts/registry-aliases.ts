#!/usr/bin/env bun
// Generates `packages/engine/src/registryAliases.generated.ts` from the local D1 catalog's
// `print_key` groups, so one REGISTRY row programs every reprint of its card.
//
//   bun scripts/registry-aliases.ts            # rewrite the table
//   bun scripts/registry-aliases.ts --check    # exit 1 if it would change
//
// The sqlite is dev state (`scripts/lib/localD1.ts`; `COLORLESS_D1_SQLITE` points elsewhere).
// Without one, `--check` skips and says so, and a rewrite fails.

import { Database } from "bun:sqlite";
import { statSync, writeFileSync } from "node:fs";
import { registryCardIds } from "@colorless/engine/testing";
import { biomeFormatted, committedText, withoutStamps } from "./lib/generated";
import { D1_DIR, D1_ENV, findLocalD1, shownD1Path } from "./lib/localD1";
import { repoPath } from "./lib/repo";

const OUT = "packages/engine/src/registryAliases.generated.ts";
const check = process.argv.includes("--check");

const dbPath = findLocalD1();
if (dbPath === undefined) {
  const where = `no local D1 sqlite under ${D1_DIR} (set ${D1_ENV} to read another)`;
  if (check) {
    console.log(`${OUT}: freshness check SKIPPED — ${where}.`);
    process.exit(0);
  }
  console.error(`${OUT}: cannot generate — ${where}.`);
  process.exit(1);
}

const db = new Database(dbPath, { readonly: true });
const stat = statSync(dbPath);
const rows = db
  .query("select id, print_key from cards where print_key is not null order by id")
  .all() as { id: string; print_key: string }[];

const groups = new Map<string, string[]>();
for (const { id, print_key } of rows) {
  const members = groups.get(print_key);
  if (members === undefined) groups.set(print_key, [id]);
  else members.push(id);
}

/** REGISTRY keys in source order, so a group's first authored row is its canonical one. */
const registryOrder = new Map(registryCardIds().map((id, i) => [id, i]));

const alias: [member: string, canonical: string][] = [];
for (const members of groups.values()) {
  if (members.length < 2) continue;
  const programmed = members
    .filter((id) => registryOrder.has(id))
    .sort((a, b) => (registryOrder.get(a) ?? 0) - (registryOrder.get(b) ?? 0));
  const canonical = programmed[0] ?? members[0];
  for (const id of members) if (id !== canonical) alias.push([id, canonical as string]);
}
alias.sort(([a, ca], [b, cb]) => (ca === cb ? (a < b ? -1 : 1) : ca < cb ? -1 : 1));

const j = (v: unknown) => JSON.stringify(v);

const source = `// Generated by \`bun scripts/registry-aliases.ts\` from the local D1 catalog; do not edit by hand.

/** The sqlite read. \`mtime\` is its last write, not the generation date. */
export const PROGRAM_ALIAS_SOURCE = {
  path: ${j(shownD1Path(dbPath))},
  mtime: ${j(stat.mtime.toISOString())},
  bytes: ${stat.size},
  generated: ${j(new Date().toISOString().slice(0, 10))},
} as const;

/**
 * Each printing that shares its catalog \`print_key\` (its name and rules text) with another, mapped
 * to its group's canonical printing: the group's REGISTRY row, or its first id when no row
 * programs it. Canonical printings and printings without a reprint are absent.
 */
export const PROGRAM_ALIAS: Readonly<Record<string, string>> = Object.freeze({
${alias.map(([id, canonical]) => `  ${j(id)}: ${j(canonical)},`).join("\n")}
});
`;

const body = biomeFormatted(OUT, source);

if (check) {
  if (withoutStamps(committedText(OUT)) !== withoutStamps(body)) {
    console.error(`${OUT} is STALE — run: bun scripts/registry-aliases.ts`);
    process.exit(1);
  }
  console.log(
    `${OUT} is current (${alias.length} aliases, sqlite mtime ${stat.mtime.toISOString()}).`,
  );
} else {
  writeFileSync(repoPath(OUT), body);
  console.log(`${OUT} written — ${alias.length} aliases over ${groups.size} print_key groups.`);
}
