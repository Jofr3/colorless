#!/usr/bin/env bun
/**
 * Fails when apps/api/worker-configuration.d.ts is not what the apps/api `types` script would
 * generate now (dependency audit VER8). That file holds the bindings `wrangler types` reads from
 * wrangler.jsonc and the Workers runtime types for its compatibility_date and the installed
 * workerd; apps/api/src/env.ts types every binding from it. Two checks, offline:
 *
 * - The header records the command that generated the file. It must be the `types` script's
 *   `wrangler types` step. A plain `wrangler types` reads apps/api/.dev.vars, so it would put a
 *   local secret's name into the committed `GeneratedEnv` and rename the interface env.ts reads.
 * - `wrangler types --check`, with the script's flags, re-hashes the bindings of wrangler.jsonc
 *   and compares the runtime header (workerd version and compatibility_date). The flags are passed
 *   again because wrangler 4.158 replays the header's `--env-file` but not its `--env-interface`.
 *   It does not compare the file's body, so the `types` script deletes the file before
 *   regenerating: wrangler otherwise keeps an existing runtime body whose header still matches.
 *
 * A step of `check:static`. Regenerate with `bun run --cwd apps/api types`.
 *
 *   bun scripts/worker-types.ts
 */

import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fail, isRecord, parseJson } from "./lib/cli";
import { localBin, repoPath } from "./lib/repo";

const GENERATED = "apps/api/worker-configuration.d.ts";
const REGENERATE = "Run `bun run --cwd apps/api types` and commit the result.";

/** Line 2 of a `wrangler types` file: "// Generated by Wrangler by running `<cmd>` (hash: <h>)". */
const HEADER = /^\/\/ Generated by Wrangler by running `([^`]+)` \(hash: [0-9a-f]+\)$/m;

/** The words of the `wrangler types ...` step of the `&&`-joined `types` script, or undefined
    when no step runs it. */
export function typesStep(script: string): string[] | undefined {
  for (const step of script.split("&&")) {
    const words = step.trim().split(/\s+/);
    if (words[0] === "wrangler" && words[1] === "types") return words;
  }
  return undefined;
}

/** What is wrong with a generated file's header, given the apps/api `types` script. */
export function headerProblems(generated: string, script: string): string[] {
  const words = typesStep(script);
  if (words === undefined) return ["the apps/api `types` script has no `wrangler types` step"];
  const step = words.join(" ");
  const recorded = HEADER.exec(generated.split("\n", 3).join("\n"))?.[1];
  if (recorded === undefined)
    return [
      `${GENERATED} has no "Generated by Wrangler by running" header in its first lines; wrangler's format may have changed, so update HEADER in scripts/worker-types.ts`,
    ];
  if (recorded !== step)
    return [
      `${GENERATED} was generated by \`${recorded}\`, not the \`types\` script's \`${step}\``,
    ];
  return [];
}

function main(): void {
  const manifest = parseJson(
    readFileSync(repoPath("apps/api/package.json"), "utf8"),
    "apps/api/package.json",
    isRecord,
  );
  const scripts = isRecord(manifest.scripts) ? manifest.scripts : {};
  const script = typeof scripts.types === "string" ? scripts.types : "";
  const generated = readFileSync(repoPath(GENERATED), "utf8");
  const header = headerProblems(generated, script);
  if (header.length > 0) fail(`worker-types: FAIL — ${header.join("; ")}. ${REGENERATE}`);
  // headerProblems found the step: its words after `wrangler types` are the flags.
  const flags = typesStep(script)?.slice(2) ?? [];
  const run = spawnSync(localBin("wrangler"), ["types", ...flags, "--check"], {
    cwd: repoPath("apps/api"),
    encoding: "utf8",
    env: { ...process.env, WRANGLER_SEND_METRICS: "false" },
  });
  if (run.status !== 0)
    fail(
      [
        `worker-types: FAIL — ${GENERATED} is out of date with wrangler.jsonc, its`,
        `compatibility_date or the installed workerd. ${REGENERATE}`,
        `${run.stdout}${run.stderr}`.trim(),
      ].join("\n"),
    );
  const runtime = /^\/\/ Runtime types generated with (\S+ \S+)$/m.exec(generated)?.[1] ?? "?";
  console.log(`worker-types: OK — ${GENERATED} is current (${runtime}).`);
}

if (import.meta.main) main();
