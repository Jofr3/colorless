#!/usr/bin/env bun
// Generates the Lua frontend's copies of TypeScript constants: the deck-size and name-length
// limits (`frontend/lua/ui/limits.lua`, `frontend/lua/web/limits.json`) and the mailbox rows'
// field columns from `src/lua/wireFields.ts` (`frontend/lua/ui/wire_fields.lua`, 1-based, and
// `frontend/lua/web/wire_fields.json`, 0-based). `frontend/lua/build.mjs` inlines the JSON files
// into host.js.
//
//   bun scripts/lua-constants.ts            # rewrite every file
//   bun scripts/lua-constants.ts --check    # exit 1 if any would change

import { readFileSync, writeFileSync } from "node:fs";
import { DECK_SIZE, DEFAULT_FORMAT, FORMATS } from "@colorless/engine";
import { DECK_NAME_MAX, DISPLAY_NAME_MAX } from "@colorless/schema";
import { type RowKind, WIRE_ROWS, wireColumn } from "../src/lua/wireFields";
import { repoPath } from "./lib/repo";

const LUA_OUT = "frontend/lua/ui/limits.lua";
const JSON_OUT = "frontend/lua/web/limits.json";
const WIRE_LUA_OUT = "frontend/lua/ui/wire_fields.lua";
const WIRE_JSON_OUT = "frontend/lua/web/wire_fields.json";

const formatSizes = [...FORMATS]
  .sort((a, b) => a.id.localeCompare(b.id))
  .map((f) => `${f.id}=${f.deckSize}`)
  .join(",");

const lua = `-- Generated by \`bun scripts/lua-constants.ts\` from the TypeScript limits; do not edit by hand.
local Limits={
  -- A game deck (engine DECK_SIZE).
  deckSize=${DECK_SIZE},
  -- A built deck's target by format id (engine deckRules.ts FORMATS).
  formatDeckSize={${formatSizes}},
  defaultFormat='${DEFAULT_FORMAT.id}',
}
-- An unknown format falls back to the default, as formatById does.
function Limits.deckSizeFor(format)
  return Limits.formatDeckSize[format] or Limits.formatDeckSize[Limits.defaultFormat]
end
return Limits
`;

const json = `${JSON.stringify({ displayNameMax: DISPLAY_NAME_MAX, deckNameMax: DECK_NAME_MAX }, null, 2)}\n`;

/** Each screen's row kinds as field name → column, offset by `base`. */
const wireColumns = (base: number) =>
  Object.fromEntries(
    Object.entries(WIRE_ROWS).map(([screen, kinds]) => [
      screen,
      Object.fromEntries(
        Object.entries(kinds as Record<string, RowKind>).map(([kind, spec]) => [
          kind,
          Object.fromEntries(spec.fields.map((field) => [field, wireColumn(spec, field) + base])),
        ]),
      ),
    ]),
  ) as Record<string, Record<string, Record<string, number>>>;

const luaTable = (entries: Record<string, number>) =>
  Object.entries(entries)
    .map(([name, column]) => `${name}=${column}`)
    .join(",");

const wireLua = `-- Generated by \`bun scripts/lua-constants.ts\` from src/lua/wireFields.ts; do not edit by hand.
-- Each mailbox row's field name to its column; a tagged row's tag is column 1.
return {
${Object.entries(wireColumns(1))
  .map(
    ([screen, kinds]) =>
      `  ${screen}={\n${Object.entries(kinds)
        .map(([kind, columns]) => `    ${kind}={${luaTable(columns)}},\n`)
        .join("")}  },\n`,
  )
  .join("")}}
`;

const wireJson = `${JSON.stringify(wireColumns(0), null, 2)}\n`;

const outputs: [string, string][] = [
  [LUA_OUT, lua],
  [JSON_OUT, json],
  [WIRE_LUA_OUT, wireLua],
  [WIRE_JSON_OUT, wireJson],
];

function current(path: string): string {
  try {
    return readFileSync(repoPath(path), "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return "";
    throw error;
  }
}

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, body]) => current(path) !== body).map(([path]) => path);
  if (stale.length > 0) {
    console.error(`${stale.join(", ")} STALE — run: bun scripts/lua-constants.ts`);
    process.exit(1);
  }
  console.log(`${outputs.map(([path]) => path).join(", ")} current.`);
} else {
  for (const [path, body] of outputs) writeFileSync(repoPath(path), body);
  console.log(`${outputs.map(([path]) => path).join(", ")} written.`);
}
