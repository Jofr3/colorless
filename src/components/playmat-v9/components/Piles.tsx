// Static-card piles displayed alongside each player: deck back, empty
// discard frame, and the 6-up prize grid. None of these participate in
// drag/drop directly — they're decorative slot frames with optional
// BalatroHoverCard tilt for the deck back / prize cards.

import type { ReactNode } from "react";
import BalatroHoverCard from "../../tcg/BalatroHoverCard";
import { SLOT_BASE, type CardBackSize, type CardBackTone } from "../types";

export function CardBackAtSize({
  tone,
  size = "card",
}: {
  tone: CardBackTone;
  size?: CardBackSize;
}) {
  return (
    <div
      className={`card-back card-back--${size}`}
      data-card-back-tone={tone}
      aria-hidden="true"
      style={{
        width: size === "prize" ? "var(--prize-w)" : "var(--card-w)",
        height: size === "prize" ? "var(--prize-h)" : "var(--card-h)",
      }}
    />
  );
}

export function PileFrame({
  children,
  active = false,
}: {
  children: ReactNode;
  active?: boolean;
}) {
  return (
    <div
      data-slot
      className={`${SLOT_BASE} ${active ? "ring-amber-300/60 shadow-[0_0_0_1px_rgba(252,211,77,0.45),0_0_28px_rgba(252,211,77,0.30),inset_0_1px_0_rgba(255,255,255,0.15)]" : ""}`}
      style={{
        width: "calc(var(--card-w) + 12px)",
        height: "calc(var(--card-h) + 12px)",
        padding: "var(--pile-pad)",
      }}
    >
      {children}
    </div>
  );
}

export function DeckPileSized({ backTone }: { backTone: CardBackTone }) {
  return (
    <div className="relative inline-block">
      <PileFrame>
        <BalatroHoverCard back={backTone}>
          <CardBackAtSize tone={backTone} />
        </BalatroHoverCard>
      </PileFrame>
    </div>
  );
}

export function DiscardPileSized() {
  return (
    <div className="relative inline-block">
      <PileFrame>
        <div style={{ width: "var(--card-w)", height: "var(--card-h)" }} />
      </PileFrame>
    </div>
  );
}

export function PrizeGridCompact({
  remaining,
  backTone,
  flip = false,
}: {
  remaining: number;
  backTone: CardBackTone;
  flip?: boolean;
}) {
  const total = 6;
  const COLS = 2;
  const ROWS = 3;
  const taken = Math.max(0, Math.min(total, total - remaining));
  const slots = Array.from({ length: total }, (_, i) =>
    flip ? i >= taken : i < total - taken,
  );
  const rows = Array.from({ length: ROWS }, (_, r) =>
    slots.slice(r * COLS, r * COLS + COLS),
  );
  return (
    <div
      data-slot
      className={SLOT_BASE}
      style={{
        width: "calc(var(--prize-w) + var(--prize-w) + var(--prize-gap-x) + 12px)",
        height:
          "calc(var(--prize-h) + var(--prize-h) + var(--prize-h) + var(--prize-gap-y) + var(--prize-gap-y) + 12px)",
        padding: "var(--pile-pad)",
      }}
    >
      <div className="flex flex-col">
        {rows.map((row, r) => (
          <div
            key={r}
            className="flex"
            style={{ marginTop: r === 0 ? 0 : "var(--prize-gap-y)" }}
          >
            {row.map((present, c) => (
              <div
                key={c}
                style={{
                  marginLeft: c === 0 ? 0 : "var(--prize-gap-x)",
                  zIndex: r * COLS + c,
                  width: "var(--prize-w)",
                  height: "var(--prize-h)",
                }}
              >
                {present && (
                  <BalatroHoverCard back={backTone} className="balatro-hover-card--prize">
                    <CardBackAtSize tone={backTone} size="prize" />
                  </BalatroHoverCard>
                )}
              </div>
            ))}
          </div>
        ))}
      </div>
    </div>
  );
}
